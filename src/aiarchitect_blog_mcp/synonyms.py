def _check_tables_are_disjoint() -> None:
    """한 표기가 두 표에 있으면 어느 규칙이 적용되는지가 코드 순서에 좌우된다.

    가드가 정반대(있어야 한다 / 없어야 한다)라 양쪽에 있는 것은 반드시 실수다.
    """
    overlap = sorted(set(QUERY_FORMS) & set(_LOOKUP))
    if overlap:
        raise ValueError(
            f"{overlap}가 SYNONYM_GROUPS와 QUERY_FORMS 양쪽에 있습니다. "
            f"코퍼스에 있으면 SYNONYM_GROUPS, 없으면 QUERY_FORMS 한 곳에만 두세요."
        )


_check_tables_are_disjoint()


def expand(term: str) -> tuple[str, ...]:
    """질의어 하나를 코퍼스가 실제로 쓰는 표기들로 넓힌다. 둘 다 해당 없으면 자기 자신만.

    질의 전용 표기가 먼저다 — 붙여 쓴 질의형을 코퍼스의 말로 되돌린 **뒤에** 동의어를 편다.
    (`검색증강생성` → `rag` → rag의 동의어 묶음). 키 자신은 넣지 않는다. 코퍼스에
    한 번도 안 나오는 것이 수록 조건이라 세어 봐야 늘 0이다.
    """
    targets = QUERY_FORMS.get(term)
    if targets is None:
        return _LOOKUP.get(term, (term,))
    widened: list[str] = []
    for target in targets:
        for variant in _LOOKUP.get(target, (target,)):
            if variant not in widened:
                widened.append(variant)
    return tuple(widened)


def variants() -> frozenset[str]:
    """`SYNONYM_GROUPS`에 등록된 모든 표기 — **코퍼스에 있어야 하는 쪽**(테스트·리포트용)."""
    return frozenset(_LOOKUP)
